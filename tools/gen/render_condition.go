package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"text/template"
)

// conditionTarget 은 조건검색 한 건이다. Target 에 trnm 만 더한 것이다.
type conditionTarget struct {
	Target
	Trnm string
}

// RenderCondition 은 조건검색 요청/응답 한 건을 만든다.
//
// REST 와 모양이 거의 같지만 전송이 WebSocket 이고, 짝짓기 열쇠가 api-id 가 아니라
// trnm 이다. 연속조회 헤더도 없다 — 이어보기는 요청 본문의 cont_yn/next_key 로 한다.
//
// 요청 구조체에서 trnm 을 **뺀다.** 값은 여기서 이미 알고 있고(호출자가 고를 수 있는 것이
// 아니다), 호출자가 비워 두면 서버 응답이 짝을 찾지 못해 ctx 만료까지 조용히 매단다.
// 대신 생성된 메서드가 직렬화 직전에 익명 래퍼로 끼워 넣는다 — 아래 conditionTmpl 참고.
func RenderCondition(t Target, trnm string) ([]byte, error) {
	t.Request = withoutTrnm(t.Request)
	var buf bytes.Buffer
	if err := conditionTmpl.Execute(&buf, conditionTarget{Target: t, Trnm: trnm}); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt 실패(%s): %w\n%s", t.GoName, err, buf.String())
	}
	return src, nil
}

// withoutTrnm 은 요청 필드에서 trnm 을 뺀다.
//
// 최상위만 본다 — trnm 은 언제나 요청 본문 맨 위에 있다(ConditionTrnm 이 같은 자리를 읽는다).
func withoutTrnm(ns []Node) []Node {
	out := make([]Node, 0, len(ns))
	for _, n := range ns {
		if n.Element == "trnm" {
			continue
		}
		out = append(out, n)
	}
	return out
}

