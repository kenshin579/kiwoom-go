package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"text/template"
)

// conditionTarget 은 조건검색 한 건이다. Target 에 trnm 만 더한 것이다.
type conditionTarget struct {
	Target
	Trnm string
}

// RenderCondition 은 조건검색 요청/응답 한 건을 만든다.
//
// REST 와 모양이 거의 같지만 전송이 WebSocket 이고, 짝짓기 열쇠가 api-id 가 아니라
// trnm 이다. 연속조회 헤더도 없다 — 이어보기는 요청 본문의 cont_yn/next_key 로 한다.
func RenderCondition(t Target, trnm string) ([]byte, error) {
	var buf bytes.Buffer
	if err := conditionTmpl.Execute(&buf, conditionTarget{Target: t, Trnm: trnm}); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt 실패(%s): %w\n%s", t.GoName, err, buf.String())
	}
	return src, nil
}

var conditionTmpl = template.Must(template.New("condition").Funcs(template.FuncMap{
	"structs": structs,
}).Parse(`// Code generated by tools/gen. DO NOT EDIT.

package {{.Package}}

import "context"

{{- $req := structs (printf "%sRequest" .GoName) .Request}}
{{- $res := structs .GoName .Response}}

// {{.GoName}}Request 는 {{.APIName}}({{.APIID}}) 요청이다.
type {{.GoName}}Request struct {
{{index $req 0}}}

// {{.GoName}}Response 는 {{.APIName}}({{.APIID}}) 응답이다.
type {{.GoName}}Response struct {
{{index $res 0}}}
{{index $res 1}}
// {{.GoName}} 는 {{.APIName}}({{.APIID}}) 이다. WebSocket 위의 요청/응답이다.
//
// 메뉴: {{.MenuPath}}
// URL:  {{.Path}}  (trnm: {{.Trnm}})
func (c *Client) {{.GoName}}(ctx context.Context, req {{.GoName}}Request) (*{{.GoName}}Response, error) {
	var out {{.GoName}}Response
	if err := c.ws.Request(ctx, "{{.Trnm}}", req, &out); err != nil {
		return nil, err
	}
	return &out, nil
}
`))
