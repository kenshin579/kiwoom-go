package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"text/template"
)

// RealtimeField 는 값 구조체의 필드 하나다.
type RealtimeField struct {
	FID    string
	Name   string
	Korean string
}

// RealtimeTarget 은 실시간 한 종류(파일 하나)다.
type RealtimeTarget struct {
	Package string
	GoName  string // 공식 영문명에서 온 메서드 이름
	Type    string // 실시간 항목 코드 (0B 등)
	APIName string
	Fields  []RealtimeField
}

// ValueType 은 값 구조체 이름이다. 메서드 이름에서 Subscribe 를 뗀다.
//
// SubscribeDomesticStockTrade 의 값이 SubscribeDomesticStockTradeValue 가 되면
// 읽기 어렵다. 접두어만 떼면 DomesticStockTrade 가 되어 자연스럽다.
func (t RealtimeTarget) ValueType() string {
	if len(t.GoName) > 9 && t.GoName[:9] == "Subscribe" {
		return t.GoName[9:]
	}
	return t.GoName + "Value"
}

// RenderRealtime 은 실시간 한 종류의 값 구조체와 구독 메서드를 만든다.
func RenderRealtime(t RealtimeTarget) ([]byte, error) {
	var buf bytes.Buffer
	if err := realtimeTmpl.Execute(&buf, t); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt 실패(%s): %w\n%s", t.GoName, err, buf.String())
	}
	return src, nil
}

var realtimeTmpl = template.Must(template.New("realtime").Parse(
	`// Code generated by tools/gen. DO NOT EDIT.

package {{.Package}}

import (
	"context"
	"encoding/json"

	"github.com/kenshin579/kiwoom-go/internal/wstransport"
	"github.com/kenshin579/kiwoom-go/stream"
)

// {{.ValueType}} 는 {{.APIName}}({{.Type}}) 의 실시간 값이다.
//
// 필드 이름은 tools/gen/fids.go 의 표에서 온다 — 스펙은 FID 숫자와 한글명만 준다.
type {{.ValueType}} struct {
{{range .Fields}}	// {{.Korean}}
	{{.Name}} string ` + "`json:\"{{.FID}}\"`" + `
{{end}}}

// {{.GoName}} 은 {{.APIName}}({{.Type}}) 을 구독한다.
//
// ctx 를 취소하면 등록을 해제하고 채널을 닫는다. 채널이 가득 차면 이벤트를 버리고
// *kiwoom.SlowConsumerError 를 흘린다 — 한 구독의 느림이 다른 구독을 굶기지 않는다.
// 끊겼다 붙으면 *kiwoom.GapError 가 온다. 그 사이 이벤트는 받지 못한 것이다.
func (c *Client) {{.GoName}}(ctx context.Context, items ...string) (<-chan stream.Event[{{.ValueType}}], error) {
	src, err := c.ws.Subscribe(ctx, "{{.Type}}", items, defaultBuffer)
	if err != nil {
		return nil, err
	}
	out := make(chan stream.Event[{{.ValueType}}], defaultBuffer)
	go func() {
		defer close(out)
		for d := range src {
			out <- decode{{.ValueType}}(d)
		}
	}()
	return out, nil
}

func decode{{.ValueType}}(d wstransport.Delivery) stream.Event[{{.ValueType}}] {
	ev := stream.Event[{{.ValueType}}]{Symbol: d.Item, Name: d.Name, Time: d.Time, Err: d.Err}
	if d.Err != nil {
		return ev
	}
	// 두 번 푼다. 구조체는 표에 있는 FID 만 받고, Raw 는 전부 받는다 —
	// 키움이 FID 를 추가했을 때 encoding/json 이 조용히 버리지 않게 한다.
	if err := json.Unmarshal(d.Values, &ev.Value); err != nil {
		ev.Err = err
		return ev
	}
	if err := json.Unmarshal(d.Values, &ev.Raw); err != nil {
		ev.Err = err
	}
	return ev
}
`))
