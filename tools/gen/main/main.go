// Command main 은 벤더링한 스펙에서 kiwoom-go 클라이언트 코드를 생성한다.
//
//	cd tools && go run ./gen/main
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"

	"github.com/kenshin579/kiwoom-go/tools/gen"
)

// generatedHeader 는 생성물의 첫 줄이다.
//
// 청소할 때 이 줄로 생성물을 가려낸다 — 같은 디렉터리에 손으로 쓴 파일
// (generated_test.go 등)이 함께 살기 때문에 디렉터리를 통째로 비울 수 없다.
const generatedHeader = "// Code generated by tools/gen. DO NOT EDIT."

// job 은 API 하나를 파일 하나로 찍는 데 필요한 것 전부다.
type job struct {
	group gen.Group
	out   string
	code  []byte
}

func main() {
	spec, err := gen.LoadSpec("spec/kiwoom_api_spec.json")
	if err != nil {
		log.Fatalf("스펙 읽기: %v", err)
	}
	names, err := gen.LoadNames("spec/api_names.json")
	if err != nil {
		log.Fatalf("이름표 읽기: %v", err)
	}

	// 1단계: 전부 메모리에서 만든다. 디스크는 아직 건드리지 않는다.
	//
	// 중간에 죽으면서 파일을 이미 써 두면 "생성기가 실패했다" 와 "트리가 바뀌었다"
	// 가 어긋난다. 실패할 일은 한 바이트도 쓰기 전에 전부 끝낸다.

	// 맵 순회 순서가 달라도 결과가 같도록 키를 정렬한다.
	keys := make([]string, 0, len(spec.APIs))
	for k := range spec.APIs {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var jobs []job
	var missing []string
	seen := map[string]string{}

	for _, k := range keys {
		api := spec.APIs[k]
		menu := api.Meta["메뉴 위치"]
		id := api.Meta["API ID"]

		g, ok := gen.Lookup(menu)
		if !ok {
			if gen.Skipped(menu) {
				continue
			}
			// 표에도 제외 목록에도 없으면 멈춘다 — 새 카테고리가 조용히 빠지면 안 된다.
			log.Fatalf("표에 없는 카테고리: %q (API %s). tools/gen/groups.go 에 넣거나 제외 목록에 적어라", menu, id)
		}

		name, ok := names[id]
		if !ok {
			// 이름표가 없으면 멈춘다. api-id 로 대충 이름을 지으면 나중에 바꿀 수 없다.
			// 하나만 보고하면 고치고 다시 돌리기를 반복하게 되니 전부 모아 한 번에 낸다.
			missing = append(missing, id)
			continue
		}

		reqTree, err := gen.BuildTree(api.Request.Body)
		if err != nil {
			log.Fatalf("%s(%s) 요청 트리: %v", id, menu, err)
		}
		resTree, err := gen.BuildTree(api.Response.Body)
		if err != nil {
			log.Fatalf("%s(%s) 응답 트리: %v", id, menu, err)
		}

		out := filepath.Join("..", g.Market, g.Pkg, name+".go")
		// 이름이 겹치면 멈춘다. 안 멈추면 API 하나가 덮어써져 소리 없이 사라진다.
		//
		// 키가 출력 경로가 아니라 GoName 인 이유: GoName 은 단사가 아니다 —
		// get_a_b 와 get_a__b 가 둘 다 GetAB 가 되고, 약어 표(API·ID 등)도 서로 다른
		// 이름을 합친다. 경로로만 보면 이런 충돌이 여기를 통과해 300개 파일 어딘가에서
		// "타입 중복 선언" 컴파일 에러로 터진다 — 여기서 또렷하게 멈추는 편이 낫다.
		key := g.Market + "/" + g.Pkg + "." + gen.GoName(name)
		if prev, dup := seen[key]; dup {
			log.Fatalf("이름 충돌: %s 와 %s 가 같은 타입 이름 %s 을 쓴다(%s)", prev, id, key, out)
		}
		seen[key] = id

		code, err := gen.Render(gen.Target{
			Package:  g.Pkg,
			GoName:   gen.GoName(name),
			APIID:    id,
			APIName:  api.Meta["API 명"],
			MenuPath: menu,
			Path:     api.Meta["URL"],
			Request:  reqTree,
			Response: resTree,
		})
		if err != nil {
			log.Fatalf("%s 렌더: %v", id, err)
		}
		jobs = append(jobs, job{group: g, out: out, code: code})
	}

	if len(missing) > 0 {
		log.Fatalf("이름표 없는 API %d개: %v", len(missing), missing)
	}

	subClients := make(map[string][]byte, len(gen.Groups))
	for _, g := range gen.Groups {
		src, err := gen.RenderSubClient(g)
		if err != nil {
			log.Fatalf("%s/%s client.go 렌더: %v", g.Market, g.Pkg, err)
		}
		subClients[filepath.Join("..", g.Market, g.Pkg, "client.go")] = src
	}
	rootWiring, err := gen.RenderClients(gen.Groups)
	if err != nil {
		log.Fatalf("subclients 렌더: %v", err)
	}

	// 2단계: 옛 생성물을 지운다.
	//
	// 생성기가 쓰기만 하면, 스펙에서 API 가 빠지거나 이름표가 바뀌었을 때 옛 파일이
	// 남아 컴파일을 통과하는 유령이 된다. 헤더가 붙은 것만 지운다.
	removed, err := cleanGenerated("..")
	if err != nil {
		log.Fatalf("옛 생성물 청소: %v", err)
	}

	// 3단계: 쓴다. 여기부터는 디스크 오류 말고는 실패할 것이 없다.
	for _, g := range gen.Groups {
		dir := filepath.Join("..", g.Market, g.Pkg)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			log.Fatalf("%s 만들기: %v", dir, err)
		}
	}
	for path, src := range subClients {
		if err := os.WriteFile(path, src, 0o644); err != nil {
			log.Fatalf("%s 쓰기: %v", path, err)
		}
	}
	if err := os.WriteFile(filepath.Join("..", "subclients.go"), rootWiring, 0o644); err != nil {
		log.Fatalf("subclients.go 쓰기: %v", err)
	}

	counts := map[string]int{}
	for _, j := range jobs {
		if err := os.WriteFile(j.out, j.code, 0o644); err != nil {
			log.Fatalf("%s 쓰기: %v", j.out, err)
		}
		counts[j.group.Market+"/"+j.group.Pkg]++
	}

	total := 0
	for _, g := range gen.Groups {
		key := g.Market + "/" + g.Pkg
		fmt.Printf("%-24s %3d개\n", key, counts[key])
		total += counts[key]
	}
	fmt.Printf("%-24s %3d개\n", "합계", total)
	fmt.Printf("지운 옛 생성물 %d개\n", removed)
}

// cleanGenerated 는 root 아래에서 생성물 헤더가 붙은 .go 파일을 지우고 개수를 돌려준다.
//
// 루트와 두 시장 디렉터리의 하위 디렉터리만 본다 — internal/·tools/ 로 내려가지 않는다.
//
// 청소 대상을 Groups 표가 아니라 **glob** 으로 훑는 이유: 표에서 그룹을 빼면 그 디렉터리가
// 청소 대상에서도 함께 빠져, 컴파일되는 유령 패키지가 남는다. subclients.go 는 그 그룹 없이
// 다시 생성되므로 아무도 안 보는 죽은 export 가 된다.
func cleanGenerated(root string) (int, error) {
	dirs := []string{root}
	for _, market := range []string{"domestic", "overseas"} {
		// 시장 디렉터리가 아직 없을 수도 있다(빈 트리에서 첫 생성). 그때는 건너뛴다.
		ents, err := os.ReadDir(filepath.Join(root, market))
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return 0, err
		}
		for _, e := range ents {
			if e.IsDir() {
				dirs = append(dirs, filepath.Join(root, market, e.Name()))
			}
		}
	}
	n := 0
	for _, dir := range dirs {
		ents, err := os.ReadDir(dir)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return n, err
		}
		for _, e := range ents {
			if e.IsDir() || filepath.Ext(e.Name()) != ".go" {
				continue
			}
			p := filepath.Join(dir, e.Name())
			b, err := os.ReadFile(p)
			if err != nil {
				return n, err
			}
			if !bytes.HasPrefix(b, []byte(generatedHeader)) {
				continue
			}
			if err := os.Remove(p); err != nil {
				return n, err
			}
			n++
		}
	}
	return n, nil
}
