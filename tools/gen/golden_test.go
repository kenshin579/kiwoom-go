// 이 테스트는 tools/gen/ 에서 돌기 때문에 main.go(tools/ 에서 돈다)와 기준 디렉터리가
// 다르다. main.go 의 "spec/..."·".." 를 그대로 베끼면 안 된다.
const (
	goldenRepoRoot = "../.."   // 저장소 루트
	goldenSpecDir  = "../spec" // 벤더링한 스펙
	goldenFixCmd   = "cd tools && go run ./gen/main"
)

// goldenHeader 는 생성물의 첫 줄이다. tools/gen/main/main.go 의 generatedHeader 와 같아야
// 한다 — 저쪽이 바뀌면 여기 orphan/mismatch 로 시끄럽게 터진다(조용히 어긋나지 않는다).
const goldenHeader = "// Code generated by tools/gen. DO NOT EDIT."

// TestGolden_생성물이_스펙과_바이트까지_같다 는 저장소에 커밋된 생성물이 지금 스펙에서
// 나오는 것과 바이트 단위로 같은지 본다.
//
// 패키지별 모양 테스트(domestic/quote/generated_test.go)는 템플릿 회귀만 잡는다 —
// api-id 하나가 틀리거나 필드 하나가 빠져도 304개 파일이 조용히 통과한다. 이 테스트
// 하나가 (a) 재생성 드리프트와 (b) 손으로 고친 생성물을 둘 다 병합 불가능하게 만든다.
//
// 이 테스트가 실패하면 **생성물이 아니라 생성기(또는 스펙)를 고치고 다시 돌려라.**
func TestGolden_생성물이_스펙과_바이트까지_같다(t *testing.T) {
	want := renderAll(t)

	var missing, mismatch []string
	for _, rel := range sortedKeys(want) {
		got, err := os.ReadFile(filepath.Join(goldenRepoRoot, rel))
		if os.IsNotExist(err) {
			missing = append(missing, rel)
			continue
		}
		if err != nil {
			t.Fatalf("%s 읽기: %v", rel, err)
		}
		if !bytes.Equal(got, want[rel]) {
			mismatch = append(mismatch, rel)
		}
	}

	orphan := findOrphans(t, want)

	report(t, "기대 목록에 있는데 디스크에 없다(missing)", missing)
	report(t, "디스크 내용이 스펙에서 나온 것과 다르다(mismatch)", mismatch)
	report(t, "생성물 헤더가 붙었는데 기대 목록에 없다(orphan)", orphan)
}

// report 는 어긋난 파일을 무엇을 하라는 말과 함께 낸다.
func report(t *testing.T, what string, files []string) {
	t.Helper()
	if len(files) == 0 {
		return
	}
	const show = 20
	list := files
	tail := ""
	if len(list) > show {
		tail = fmt.Sprintf("\n  ... 외 %d개", len(list)-show)
		list = list[:show]
	}
	t.Errorf("생성물이 스펙과 다르다(%d개) — %s. %s 으로 다시 생성하라.\n  %v%s",
		len(files), what, goldenFixCmd, list, tail)
}

// renderAll 은 main.go 와 같은 순서·같은 입력으로 전부 메모리에서 렌더한다.
// 키는 저장소 루트 기준 상대 경로다.
func renderAll(t *testing.T) map[string][]byte {
	t.Helper()

	spec, err := gen.LoadSpec(filepath.Join(goldenSpecDir, "kiwoom_api_spec.json"))
	if err != nil {
		t.Fatalf("스펙 읽기: %v", err)
	}
	names, err := gen.LoadNames(filepath.Join(goldenSpecDir, "api_names.json"))
	if err != nil {
		t.Fatalf("이름표 읽기: %v", err)
	}

	out := map[string][]byte{}

	keys := make([]string, 0, len(spec.APIs))
	for k := range spec.APIs {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, k := range keys {
		api := spec.APIs[k]
		menu := api.Meta["메뉴 위치"]
		id := api.Meta["API ID"]

		g, ok := gen.Lookup(menu)
		if !ok {
			if gen.Skipped(menu) {
				continue
			}
			t.Fatalf("표에 없는 카테고리: %q (API %s). tools/gen/groups.go 를 고쳐라", menu, id)
		}
		name, ok := names[id]
		if !ok {
			t.Fatalf("이름표 없는 API: %s (%s)", id, menu)
		}

		reqTree, err := gen.BuildTree(api.Request.Body)
		if err != nil {
			t.Fatalf("%s(%s) 요청 트리: %v", id, menu, err)
		}
		resTree, err := gen.BuildTree(api.Response.Body)
		if err != nil {
			t.Fatalf("%s(%s) 응답 트리: %v", id, menu, err)
		}

		code, err := gen.Render(gen.Target{
			Package:  g.Pkg,
			GoName:   gen.GoName(name),
			APIID:    id,
			APIName:  api.Meta["API 명"],
			MenuPath: menu,
			Path:     api.Meta["URL"],
			Request:  reqTree,
			Response: resTree,
		})
		if err != nil {
			t.Fatalf("%s 렌더: %v", id, err)
		}
		out[filepath.Join(g.Market, g.Pkg, name+".go")] = code
	}

	for _, g := range gen.Groups {
		src, err := gen.RenderSubClient(g)
		if err != nil {
			t.Fatalf("%s/%s client.go 렌더: %v", g.Market, g.Pkg, err)
		}
		out[filepath.Join(g.Market, g.Pkg, "client.go")] = src
	}
	root, err := gen.RenderClients(gen.Groups)
	if err != nil {
		t.Fatalf("subclients 렌더: %v", err)
	}
	out["subclients.go"] = root

	return out
}

// findOrphans 는 디스크에서 생성물 헤더가 붙었는데 기대 목록에 없는 파일을 찾는다.
//
// 표(Groups)가 아니라 glob 으로 훑는다 — 표에서 그룹을 빼면 그 디렉터리가 검사에서도
// 함께 빠져 유령 패키지가 남기 때문이다(cleanGenerated 와 같은 이유).
func findOrphans(t *testing.T, want map[string][]byte) []string {
	t.Helper()

	dirs := []string{""}
	for _, market := range []string{"domestic", "overseas"} {
		ents, err := os.ReadDir(filepath.Join(goldenRepoRoot, market))
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			t.Fatalf("%s 읽기: %v", market, err)
		}
		for _, e := range ents {
			if e.IsDir() {
				dirs = append(dirs, filepath.Join(market, e.Name()))
			}
		}
	}

	var orphan []string
	for _, dir := range dirs {
		ents, err := os.ReadDir(filepath.Join(goldenRepoRoot, dir))
		if err != nil {
			t.Fatalf("%s 읽기: %v", dir, err)
		}
		for _, e := range ents {
			if e.IsDir() || filepath.Ext(e.Name()) != ".go" {
				continue
			}
			rel := filepath.Join(dir, e.Name())
			if _, ok := want[rel]; ok {
				continue
			}
			b, err := os.ReadFile(filepath.Join(goldenRepoRoot, rel))
			if err != nil {
				t.Fatalf("%s 읽기: %v", rel, err)
			}
			if bytes.HasPrefix(b, []byte(goldenHeader)) {
				orphan = append(orphan, rel)
			}
		}
	}
	sort.Strings(orphan)
	return orphan
}

func sortedKeys(m map[string][]byte) []string {
	ks := make([]string, 0, len(m))
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}
